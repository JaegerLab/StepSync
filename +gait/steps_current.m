function tf = steps_current(data)
%STEPS_CURRENT True only after successful calculation for the live selection.
%   The selection (data.gait.selection) is kept in sync by the gait viewer.
tf = data.has('gait') && isfield(data.gait, 'stepsValid') && data.gait.stepsValid ...
    && isfield(data.gait, 'stepsPaw') && isfield(data.gait, 'stepsTrace') ...
    && isfield(data.gait, 'selection') ...
    && isequal(data.gait.stepsPaw, data.gait.selection.paw) ...
    && strcmp(data.gait.stepsTrace, data.gait.selection.trace);
end
